ROOT = Path(__file__).resolve().parents[1]
MARKER = "Generated by scripts/generate.py from palette/palette.json. Do not edit."


def lua_value(value: Any, depth: int = 0) -> str:
    indent = "  " * depth
    child_indent = "  " * (depth + 1)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        if value and isinstance(value[0], dict) and "hex" in value[0]:
            value = [entry["hex"] for entry in value]
        body = ",\n".join(f"{child_indent}{lua_value(child, depth + 1)}" for child in value)
        return "{\n" + body + f"\n{indent}}}"
    if isinstance(value, dict):
        body = ",\n".join(
            f"{child_indent}{key} = {lua_value(child, depth + 1)}" for key, child in value.items()
        )
        return "{\n" + body + f"\n{indent}}}"
    raise TypeError(f"cannot serialize {type(value).__name__} to Lua")


def generated_lua_palette(style: str, mode: dict[str, Any]) -> str:
    runtime_mode = dict(mode)
    runtime_mode["style"] = style
    return f"-- {MARKER}\nreturn {lua_value(runtime_mode)}\n"


def generated_entry(style: str) -> str:
    return (
        f"-- {MARKER}\n"
        f"require(\"quireveil\").load(\"{style}\", \"quireveil{'' if style == 'auto' else '-' + style}\")\n"
    )


def generated_ghostty(style: str, mode: dict[str, Any]) -> str:
    title = f"Quireveil {style.title()}"
    lines = [
        f"# {MARKER}",
        f"# {title} — opaque core theme",
        f"background = {mode['background']}",
        f"foreground = {mode['foreground']['primary']}",
        f"cursor-color = {mode['cursor']['background']}",
        f"cursor-text = {mode['cursor']['foreground']}",
        f"selection-background = {mode['selection']['background']}",
        f"selection-foreground = {mode['selection']['foreground']}",
    ]
    lines.extend(f"palette = {entry['index']}={entry['hex']}" for entry in mode["ansi"])
    return "\n".join(lines) + "\n"


def css_name(path: str) -> str:
    return "--q-" + path.replace(".", "-").replace("_", "-")


def generated_css(palette: dict[str, Any]) -> str:
    blocks = [f"/* {MARKER} */"]
    for style, mode in palette["modes"].items():
        selector = ":root, [data-theme=\"light\"]" if style == "light" else "[data-theme=\"dark\"]"
        blocks.append(f"{selector} {{")
        for path, color in iter_colors(mode):
            if ".hex" in path:
                continue
            blocks.append(f"  {css_name(path)}: {color};")
        for entry in mode["ansi"]:
            blocks.append(f"  --q-ansi-{entry['index']}: {entry['hex']};")
        blocks.append("}")
    return "\n".join(blocks) + "\n"


def generated_javascript(palette: dict[str, Any]) -> str:
    data = json.dumps(palette, indent=2, sort_keys=True)
    return f"/* {MARKER} */\nwindow.QUIREVEIL_PALETTE = {data};\n"


def generated_export(palette: dict[str, Any]) -> str:
    export = {
        "generated": MARKER,
        "meta": palette["meta"],
        "modes": {
            style: {
                "roles": {path: color for path, color in iter_colors(mode) if ".hex" not in path},
                "ansi": ansi_colors(mode),
            }
            for style, mode in palette["modes"].items()
        },
    }
    return json.dumps(export, indent=2, sort_keys=True) + "\n"


