def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of writing when generated files drift")
    args = parser.parse_args()

    expected = render_files(load_palette(ROOT))
    drift: list[str] = []
    for relative, content in expected.items():
        destination = ROOT / relative
        if args.check:
            if not destination.exists() or destination.read_text(encoding="utf-8") != content:
                drift.append(str(relative))
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")

    if drift:
        print("generated files are missing or stale:", file=sys.stderr)
        for path in drift:
            print(f"  {path}", file=sys.stderr)
        print("run: python3 scripts/generate.py", file=sys.stderr)
        return 1
    if not args.check:
        print(f"generated {len(expected)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
