def generated_color_vision(palette: dict[str, Any]) -> str:
    lines = [
        f"<!-- {MARKER} -->",
        "# Colour-vision report",
        "",
        "This deterministic screen uses full-severity linear-sRGB simulation matrices and OKLab distance as a regression signal. It is a design check, not a diagnosis or accessibility certification. Smaller distances mean hues may converge.",
        "",
        "| Mode | Pair | Original | Protanopia | Deuteranopia | Tritanopia |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for style, mode in palette["modes"].items():
        for first_path, second_path, label in CVD_PAIRS:
            first = get_path(mode, first_path)
            second = get_path(mode, second_path)
            values = [oklab_distance(first, second)]
            values.extend(oklab_distance(first, second, name) for name in CVD_MATRICES)
            lines.append(
                f"| {style} | {label} | " + " | ".join(f"{value:.3f}" for value in values) + " |"
            )
    lines.extend(
        [
            "",
            "Hue is never the only carrier of critical state. Diagnostics add `E`/`W`/`I`/`H` gutter signs and severity-specific undercurls; deprecated tokens use strikethrough. Diffs combine signs with separate surface and inline-text tints. Selection and search use distinct backgrounds and current-search contrast.",
        ]
    )
    return "\n".join(lines) + "\n"


def render_files(palette: dict[str, Any]) -> dict[Path, str]:
    files: dict[Path, str] = {
        Path("colors/quireveil.lua"): generated_entry("auto"),
        Path("colors/quireveil-light.lua"): generated_entry("light"),
        Path("colors/quireveil-dark.lua"): generated_entry("dark"),
        Path("ghostty/themes/Quireveil Light"): generated_ghostty("light", palette["modes"]["light"]),
        Path("ghostty/themes/Quireveil Dark"): generated_ghostty("dark", palette["modes"]["dark"]),
        Path("preview/generated/palette.css"): generated_css(palette),
        Path("preview/generated/palette.js"): generated_javascript(palette),
        Path("dist/quireveil-palette.json"): generated_export(palette),
        Path("docs/generated/CONTRAST.md"): generated_contrast(palette),
        Path("docs/generated/ANSI.md"): generated_ansi(palette),
        Path("docs/generated/COLOR_VISION.md"): generated_color_vision(palette),
    }
    for style, mode in palette["modes"].items():
        files[Path(f"lua/quireveil/palette/{style}.lua")] = generated_lua_palette(style, mode)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of writing when generated files drift")
    args = parser.parse_args()

    expected = render_files(load_palette(ROOT))
    drift: list[str] = []
    for relative, content in expected.items():
        destination = ROOT / relative
        if args.check:
            if not destination.exists() or destination.read_text(encoding="utf-8") != content:
                drift.append(str(relative))
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")

    if drift:
        print("generated files are missing or stale:", file=sys.stderr)
        for path in drift:
            print(f"  {path}", file=sys.stderr)
        print("run: python3 scripts/generate.py", file=sys.stderr)
        return 1
    if not args.check:
        print(f"generated {len(expected)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
