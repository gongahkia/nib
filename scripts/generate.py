def generated_contrast(palette: dict[str, Any]) -> str:
    lines = [
        f"<!-- {MARKER} -->",
        "# Contrast report",
        "",
        "Ratios use WCAG 2 relative luminance on the authored opaque sRGB colors. Passing these targeted checks is not blanket accessibility certification.",
        "",
        "| Mode | Use | Foreground | Background | Ratio | Target | Result |",
        "| --- | --- | --- | --- | ---: | ---: | --- |",
    ]
    for style, mode in palette["modes"].items():
        for foreground_path, background_path, target, label in CONTRAST_PAIRS:
            foreground = get_path(mode, foreground_path)
            background = get_path(mode, background_path)
            ratio = contrast(foreground, background)
            result = "pass" if ratio + 1e-9 >= target else "**FAIL**"
            lines.append(
                f"| {style} | {label} | `{foreground}` | `{background}` | {ratio:.2f}:1 | {target:.1f}:1 | {result} |"
            )
    return "\n".join(lines) + "\n"


