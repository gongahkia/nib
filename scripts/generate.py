def generated_contrast(palette: dict[str, Any]) -> str:
    lines = [
        f"<!-- {MARKER} -->",
        "# Contrast report",
        "",
        "Ratios use WCAG 2 relative luminance on the authored opaque sRGB colors. Passing these targeted checks is not blanket accessibility certification.",
        "",
        "| Mode | Use | Foreground | Background | Ratio | Target | Result |",
        "| --- | --- | --- | --- | ---: | ---: | --- |",
    ]
    for style, mode in palette["modes"].items():
        for foreground_path, background_path, target, label in CONTRAST_PAIRS:
            foreground = get_path(mode, foreground_path)
            background = get_path(mode, background_path)
            ratio = contrast(foreground, background)
            result = "pass" if ratio + 1e-9 >= target else "**FAIL**"
            lines.append(
                f"| {style} | {label} | `{foreground}` | `{background}` | {ratio:.2f}:1 | {target:.1f}:1 | {result} |"
            )
    return "\n".join(lines) + "\n"


def generated_ansi(palette: dict[str, Any]) -> str:
    lines = [
        f"<!-- {MARKER} -->",
        "# ANSI palette",
        "",
        "Indexes retain conventional terminal identities. On the light background, bright variants are optically stronger but are not required to be lighter than their normal partner; this keeps terminal text readable.",
        "",
        "| Index | Identity | Light | Contrast | Dark | Contrast |",
        "| ---: | --- | --- | ---: | --- | ---: |",
    ]
    light = palette["modes"]["light"]
    dark = palette["modes"]["dark"]
    for light_entry, dark_entry in zip(light["ansi"], dark["ansi"]):
        lines.append(
            "| {index} | {name} | `{light}` | {light_ratio:.2f}:1 | `{dark}` | {dark_ratio:.2f}:1 |".format(
                index=light_entry["index"],
                name=light_entry["name"],
                light=light_entry["hex"],
                light_ratio=contrast(light_entry["hex"], light["background"]),
                dark=dark_entry["hex"],
                dark_ratio=contrast(dark_entry["hex"], dark["background"]),
            )
        )
    lines.extend(
        [
            "",
            "ANSI index 0 intentionally remains a low-contrast near-black swatch in dark mode: terminal black is a background/building color, not a general prose color. Indices 1–15 meet the ordinary-text target against the mode background.",
        ]
    )
    return "\n".join(lines) + "\n"


